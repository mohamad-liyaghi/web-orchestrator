import type { Settings } from './types';
import { DEFAULT_SETTINGS } from './settings';

/** One-tap setups shown in the controls. Each is a settings patch on top of the current settings. */
export interface Preset {
  id: string;
  name: string;
  /** Short glyph for the chip. */
  glyph: string;
  description: string;
  settings: Partial<Settings>;
}

/**
 * Style fields every preset starts from, so a preset never inherits the previous one's feel
 * (a waltz's 3/4 or a skank's palm mute). Personal setup like tuning, transpose, EQ, touch and
 * the count-in is left alone.
 */
const STYLE_KEYS = [
  'playStyle',
  'strumPattern',
  'arpPattern',
  'arpRate',
  'arpOctaves',
  'bassPattern',
  'voicing',
  'harmony',
  'sustainPedal',
  'palmMute',
  'glide',
  'humanize',
  'timeSignature',
  'swing',
  'reverbType',
  'delay',
  'delayTime',
  'delayFeedback',
  'chorus',
  'width',
] as const satisfies ReadonlyArray<keyof Settings>;

const STYLE_BASE: Partial<Settings> = Object.fromEntries(STYLE_KEYS.map((k) => [k, DEFAULT_SETTINGS[k]]));

const preset = (id: string, name: string, glyph: string, description: string, settings: Partial<Settings>): Preset => ({
  id,
  name,
  glyph,
  description,
  settings: { ...STYLE_BASE, ...settings },
});

